const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');

const modules = new Map();
let rejectMutation = false;
const api = { get: async () => ({ data: [] }), post: async () => { if (rejectMutation) throw new Error('Falha simulada'); return { data: {} }; }, put: async () => { if (rejectMutation) throw new Error('Falha simulada'); return { data: {} }; } };
function load(relative) {
  if (modules.has(relative)) return modules.get(relative);
  const source = fs.readFileSync(path.join(__dirname, '..', relative), 'utf8');
  const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
  const module = { exports: {} };
  vm.runInNewContext(compiled.outputText, { module, exports: module.exports, Date, Map, Set, URLSearchParams, require: (name) => {
    if (name === 'react') return {};
    if (name === '@/services/api' || name === './api') return { api };
    if (name === '@/lib/adminCache') return load('src/lib/adminCache.ts');
    if (name === './queryCache') return load('src/lib/queryCache.ts');
    if (name === './consoleNavigation') return load('src/components/admin/console/consoleNavigation.ts');
    throw new Error(`Import inesperado: ${name}`);
  } });
  modules.set(relative, module.exports);
  return module.exports;
}

async function main() {
  const { companyEditorPath, resolveCompanyEditorTab } = load('src/components/admin/console/companyEditorNavigation.ts');
  assert.equal(companyEditorPath(7, 'data'), '/admin/empresas/7/editar');
  assert.equal(companyEditorPath(7, 'appearance'), '/admin/empresas/7/editar?aba=aparencia');
  assert.equal(companyEditorPath(12, 'features'), '/admin/empresas/12/editar?aba=funcionalidades');
  assert.equal(resolveCompanyEditorTab('?aba=aparencia'), 'appearance');
  assert.equal(resolveCompanyEditorTab('?aba=funcionalidades'), 'features');
  assert.equal(resolveCompanyEditorTab('?aba=invalid'), 'data');
  assert.equal(resolveCompanyEditorTab('', 'appearance'), 'appearance');
  const { normalizeAdminListFilters } = load('src/hooks/useAdminListFilters.ts');
  const invalidFilters = normalizeAdminListFilters({ page: -5, pageSize: 100000, search: 123, sort: 'invalid', status: 'invalid' }, 'asc');
  assert.equal(invalidFilters.page, 1);
  assert.equal(invalidFilters.pageSize, 25);
  assert.equal(invalidFilters.search, '');
  assert.equal(invalidFilters.sort, 'asc');
  assert.equal(invalidFilters.status, '');
  assert.equal(normalizeAdminListFilters(null).page, 1);
  assert.equal(normalizeAdminListFilters({ page: 4, pageSize: 100, search: 'Escola', sort: 'desc', status: 'active' }).pageSize, 100);
  const { resolveConsolePage } = load('src/components/admin/console/consoleNavigation.ts');
  const { adminBreadcrumbs } = load('src/components/admin/console/adminBreadcrumbs.ts');
  const companyTrail = adminBreadcrumbs('/admin/empresas/7/editar', true);
  assert.equal(companyTrail[0].to, '/admin/inicio');
  assert.equal(companyTrail[1].to, '/admin/empresas');
  assert.equal(companyTrail[2].label, 'Editar empresa');
  assert.equal(companyTrail[2].to, undefined);
  assert.equal(adminBreadcrumbs('/admin/empresas/7/pessoas/usuarios/4/editar', true, '/admin/pessoas/usuarios?empresa=7')[1].to, '/admin/pessoas/usuarios?empresa=7');
  assert.equal(adminBreadcrumbs('/admin/pessoas/usuarios/4/editar', false, 'https://example.com')[1].to, '/admin/pessoas/usuarios');
  assert.equal(adminBreadcrumbs('/admin/configuracoes/dados', false).length, 2);
  const { platformSectionPath, platformCompanyId, platformPageCompanyId } = load('src/components/admin/console/platformNavigation.ts');
  assert.equal(platformPageCompanyId('edit-user', null, '7'), undefined);
  assert.equal(platformPageCompanyId('edit-user', 7, '20'), 7);
  assert.equal(platformPageCompanyId('users', null, '20'), 20);
  assert.equal(platformSectionPath('users'), '/admin/pessoas/usuarios');
  assert.equal(platformSectionPath('edit-company'), '/admin/empresas');
  assert.equal(platformSectionPath('edit-user'), '/admin/pessoas/usuarios');
  assert.equal(platformCompanyId('7'), 7);
  assert.equal(platformCompanyId(''), undefined);
  assert.throws(() => platformCompanyId('-1'));
  assert.throws(() => platformCompanyId('bad'));
  const { hasAdminConsoleAccess, resolveAdminConsoleScope } = load('src/components/admin/console/consoleNavigation.ts');
  assert.equal(hasAdminConsoleAccess({ role: 'user' }), false);
  assert.equal(resolveAdminConsoleScope({ role: 'admin', empresa_id: 8 }).empresaId, 8);
  assert.equal(resolveAdminConsoleScope({ role: 'platform_admin', empresa_id: null }).kind, 'platform');
  const cache = load('src/lib/queryCache.ts');
  const { adminQueryKey, invalidateAdminResources } = load('src/lib/adminCache.ts');
  const { companyCacheKey } = load('src/config/features.ts');
  const service = load('src/services/admin.ts');
  const people = load('src/services/convites.ts');
  const platform = load('src/services/platformRecords.ts');
  for (const [suffix, id] of [['auditoria/configuracoes', 'audit-settings'], ['auditoria/eventos', 'audit-events'], ['configuracoes/dados', 'data'], ['configuracoes/aparencia', 'appearance'], ['configuracoes/funcionalidades', 'features'], ['pessoas/usuarios', 'users'], ['operacao/pilotos/7/editar', 'edit-pilot']]) {
    assert.equal(resolveConsolePage(`/admin/empresas/10/${suffix}`).id, id);
  }
  assert.equal(resolveConsolePage('/admin/empresas/10/qualquer/configuracoes').id, 'unavailable');
  assert.equal(resolveConsolePage('/admin/pessoas/usuarios').list, true);
  assert.equal(resolveConsolePage('/admin/empresas').title, 'Cadastro');
  assert.equal(resolveConsolePage('/admin/empresas/7/editar').id, 'edit-company');
  assert.equal(resolveConsolePage('/admin/empresas/10/pessoas/usuarios/7/editar').id, 'edit-user');
  assert.equal(resolveConsolePage('/admin/pessoas/usuarios/7/editar').list, undefined);
  assert.equal(resolveConsolePage('/admin/pessoas/usuarios/0/editar').id, 'unavailable');
  const originalGet = api.get;
  const detailRequests = [];
  api.get = async (url) => { detailRequests.push(url); return { data: { id: 7 } }; };
  assert.equal((await people.obterUsuario(7, 10)).id, 7);
  await people.obterUsuario(7);
  assert.deepEqual(detailRequests, ['/platform/admin/empresas/10/usuarios/7', '/admin/empresa/usuarios/7']);
  await platform.listPlatformRecords('users', { page: 2, pageSize: 50 });
  await platform.listPlatformRecords('users', { page: 1, pageSize: 25, empresaId: 7, search: 'Ana' });
  assert.equal(detailRequests[2], '/platform/admin/registros/users?page=2&pageSize=50');
  assert.equal(detailRequests[3], '/platform/admin/registros/users?page=1&pageSize=25&empresaId=7&search=Ana');
  api.get = originalGet;
  const user = { userId: 1, role: 'platform_admin', empresa_id: null, empresa_parametros: {} };
  const key = (resource, company, filters, session = user) => companyCacheKey(adminQueryKey(resource, company, filters), session);
  const first = key('users', 10, { page: 1 });
  const platformKey = companyCacheKey('admin:platform:records:users:all', user);
  cache.setCache(platformKey, 'platform-page');
  invalidateAdminResources(10, 'users');
  assert.equal(cache.getCached(platformKey), null);
  const secondPage = key('users', 10, { page: 2 });
  const otherCompany = key('users', 20, { page: 1 });
  const otherSession = key('users', 10, { page: 1 }, { ...user, userId: 2 });
  assert.notEqual(first, otherCompany);
  assert.notEqual(first, otherSession);
  cache.setCache(first, 'original');
  assert.equal(cache.getCached(otherSession), null);
  let calls = 0;
  let resolveOld;
  cache.clearQueryCache();
  const old = cache.fetchCached(first, () => { calls++; return new Promise((resolve) => { resolveOld = resolve; }); });
  const duplicate = cache.fetchCached(first, () => { calls++; return Promise.resolve('duplicate'); });
  assert.equal(calls, 1);
  assert.equal(old, duplicate);
  cache.setCache(secondPage, 'second-page');
  cache.setCache(otherCompany, 'other-company');
  cache.invalidatePrefix(adminQueryKey('users', 10));
  assert.equal(cache.getCached(secondPage), null);
  assert.equal(cache.getCached(otherCompany), 'other-company');
  await cache.fetchCached(first, async () => 'updated');
  resolveOld('obsolete');
  await old;
  assert.equal(cache.getCached(first), 'updated');
  assert.equal(cache.isStale(first), false);
  cache.setCache(key('summary', 10), 'summary');
  cache.setCache(key('audit-events', 10), 'events');
  await people.inativarUsuario(7, 'Motivo fictício', 10);
  assert.equal(cache.getCached(first), null);
  assert.equal(cache.getCached(key('summary', 10)), null);
  assert.equal(cache.getCached(key('audit-events', 10)), null);
  assert.equal(cache.getCached(otherCompany), 'other-company');
  const theme = key('theme', 10);
  cache.setCache(theme, 'theme');
  cache.setCache(key('audit-settings', 10), 'history');
  cache.setCache(key('companies'), 'companies');
  await service.updateTema({ logo_url: null }, 10);
  assert.equal(cache.getCached(theme), null);
  assert.equal(cache.getCached(key('audit-settings', 10)), null);
  assert.equal(cache.getCached(key('companies')), null);
  cache.setCache(theme, 'preserved');
  const originalPut = api.put;
  const settingsRequests = [];
  const combined = { nome: 'Empresa de teste', logo_url: null, paleta: { primary: '#112233' }, parametros: { rankingEnabled: true, globalRankingEnabled: false, achievementsEnabled: true, enabledGames: [] } };
  api.put = async (url, payload) => { settingsRequests.push({ url, payload }); return { data: { tema: {}, parametros: payload.parametros } }; };
  await service.updateCompanySettings(10, combined);
  assert.equal(settingsRequests.length, 1);
  assert.equal(settingsRequests[0].url, '/platform/admin/empresas/10/configuracoes');
  assert.equal(settingsRequests[0].payload, combined);
  api.put = originalPut;
  cache.setCache(theme, 'preserved');
  rejectMutation = true;
  await assert.rejects(service.updateTema({ logo_url: null }, 10));
  assert.equal(cache.getCached(theme), 'preserved');
  cache.clearQueryCache();
  assert.equal(cache.getCached(otherCompany), null);
  console.log('Rotas exatas, separação por sessão/empresa, deduplicação, resposta tardia e invalidação após mutações aprovadas.');
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
